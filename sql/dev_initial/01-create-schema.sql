CREATE TABLE "organization" (
    -- PK
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    -- Properties
    name varchar(256) NOT NULL
    );

CREATE TABLE "bsp"(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    -- Properties
    name varchar(256) NOT NULL,
    country varchar(3) NOT NULL,
    -- FK
    org_id BIGINT NOT NULL REFERENCES "organization"(id) ON DELETE CASCADE,
    -- Constraints
    UNIQUE(id,org_id)
);

CREATE TABLE "brp"(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    -- Properties
    name varchar(256) NOT NULL,
    country varchar(3) NOT NULL,
    -- FK
    org_id BIGINT NOT NULL REFERENCES "organization"(id) ON DELETE CASCADE,
    -- Constraints
    UNIQUE(id,org_id)
);

CREATE TABLE "asset" (
    -- PK
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    -- Properties
    name varchar(256) NOT NULL,
    country varchar(3) NOT NULL,
    -- FKs
    org_id BIGINT NOT NULL REFERENCES "organization"(id) ON DELETE CASCADE,
    bsp_id BIGINT,
    brp_id BIGINT NOT NULL
);

-- An asset can only belong to a unique bsp of its organization.
ALTER TABLE "asset" ADD CONSTRAINT fk_asset_bsp_org
    FOREIGN KEY (bsp_id,org_id) REFERENCES "bsp"(id,org_id) ON DELETE SET NULL(bsp_id);

-- An asset must belong to a unique brp of its organization.
ALTER TABLE "asset" ADD CONSTRAINT fk_asset_brp_org
    FOREIGN KEY (brp_id,org_id) REFERENCES "brp"(id,org_id);

CREATE TABLE "country"(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    -- Properties
    code varchar(3) NOT NULL UNIQUE
);
