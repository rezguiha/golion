CREATE TABLE "asset" (
    -- PK
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    -- Properties
    name varchar(256) NOT NULL,
    country varchar(3) NOT NULL,
    -- FKs
    bsp_id BIGINT
);

CREATE TABLE "country"(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    -- Properties
    code varchar(3) NOT NULL UNIQUE
);

CREATE TABLE "bsp"(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    -- Properties
    name varchar(256) NOT NULL,
    country varchar(3) NOT NULL
);


CREATE TABLE "brp"(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    name varchar(256) NOT NULL,
    country varchar(3) NOT NULL
);
