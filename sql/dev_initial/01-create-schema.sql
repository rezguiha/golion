CREATE TABLE "organization" (
    -- PK
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    -- Properties
    name varchar(256) NOT NULL
    );

CREATE TABLE "user" (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    org_id   BIGINT NOT NULL REFERENCES "organization"(id) ON DELETE CASCADE,
    username varchar(128) NOT NULL UNIQUE
);

CREATE TABLE "country"(
    -- Properties
    code char(3) PRIMARY KEY
);

CREATE TYPE ancillary_service_type AS ENUM ('Fcr','Afrr','AfrrFree');

CREATE TABLE "ancillary_market"(
    country char(3) NOT NULL REFERENCES "country"(code),
    service_type ancillary_service_type NOT NULL,
    PRIMARY KEY(country,service_type)
);

CREATE TABLE "bsp"(
    -- PK
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    -- FK
    org_id BIGINT NOT NULL REFERENCES "organization"(id) ON DELETE CASCADE,
    -- Properties
    name varchar(256) NOT NULL,
    country char(3) NOT NULL,
    service_type ancillary_service_type NOT NULL,
    -- Constraints
    FOREIGN KEY (country,service_type) REFERENCES "ancillary_market"(country,service_type),
    UNIQUE(id,org_id,country, service_type)

);

CREATE TABLE "brp"(
    -- PK
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    -- FK
    org_id BIGINT NOT NULL REFERENCES "organization"(id) ON DELETE CASCADE,
    -- Properties
    name varchar(256) NOT NULL,
    country char(3) NOT NULL,
    -- Constraints
    UNIQUE(id,org_id)
);

CREATE TABLE "asset" (
    -- PK
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    -- FKs
    org_id BIGINT NOT NULL REFERENCES "organization"(id) ON DELETE CASCADE,
    brp_id BIGINT NOT NULL,
    -- Properties
    name varchar(256) NOT NULL,
    country char(3) NOT NULL,
    -- Constraints
    UNIQUE (id, org_id, country),
    -- An asset must belong to a unique brp of its organization.
    FOREIGN KEY (brp_id,org_id) REFERENCES "brp"(id,org_id)
);

-- Association table to enforce that an asset can belong to at most
-- on bsp per ancillary service from its organization and country.
CREATE TABLE "asset_bsp_association"(
    asset_id BIGINT NOT NULL,
    org_id BIGINT NOT NULL,
    bsp_id BIGINT NOT NULL,
    country char(3),
    service_type ancillary_service_type NOT NULL,
    PRIMARY KEY (asset_id,service_type),
    FOREIGN KEY (asset_id,org_id,country) REFERENCES "asset"(id,org_id,country) ON DELETE CASCADE,
    FOREIGN KEY (bsp_id,org_id,country,service_type) REFERENCES "bsp"(id,org_id,country,service_type) ON DELETE CASCADE
);
